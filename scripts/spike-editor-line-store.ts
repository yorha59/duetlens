import { strict as assert } from 'node:assert';
import { EditorLineStore } from '../src/renderer/screens/review/editor-line-store';

const store = new EditorLineStore();
const calls = [0, 0, 0];
const off = ['a.ts', 'b.ts', 'c.ts'].map((path, index) => store.subscribe(path, () => calls[index]++));
assert.equal(store.get('a.ts'), null);
store.select({ path: 'a.ts', line: 42 });
assert.equal(store.get('a.ts'), 42);
assert.deepEqual(calls, [1, 0, 0]);
store.select({ path: 'a.ts', line: 42 });
assert.deepEqual(calls, [1, 0, 0]);
store.select({ path: 'a.ts', line: 43 });
assert.deepEqual(calls, [2, 0, 0]);
store.select({ path: 'b.ts', line: 7 });
assert.equal(store.get('a.ts'), null);
assert.equal(store.get('b.ts'), 7);
assert.deepEqual(calls, [3, 1, 0]);
store.select(null);
assert.equal(store.get('b.ts'), null);
assert.deepEqual(calls, [3, 2, 0]);
off.forEach((unsubscribe) => unsubscribe());
store.select({ path: 'c.ts', line: 1 });
assert.deepEqual(calls, [3, 2, 0]);
const unsubscribe = store.subscribe('c.ts', () => calls[2]++);
store.select({ path: 'c.ts', line: 2 });
assert.deepEqual(calls, [3, 2, 1]);
unsubscribe();
console.log('editor line subscriptions: passed (only affected headers notified)');
