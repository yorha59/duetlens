/** 实际 HTTP + SQLite + Git 快照验证,不起模型、不访问用户仓库或外部服务。 */
import { request } from 'node:http';
import { strict as assert } from 'node:assert';
import { execFile } from 'node:child_process';
import { mkdtemp, mkdir, readFile, rm, symlink, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { promisify } from 'node:util';
import { openDatabase } from '../src/backend/db/database';
import { ReviewStore } from '../src/backend/db/review-store';
import { LocalWorktreeSource } from '../src/backend/source/local-worktree-source';
import { SharedSessionReader, isShareFilePath } from '../src/backend/share/session-reader';
import { SessionShareServer } from '../src/backend/share/session-share-server';

const exec = promisify(execFile);
async function main() {
  const root = await mkdtemp(path.join(os.tmpdir(), 'duetlens-share-'));
  const repo = path.join(root, 'repo');
  const snapshots = path.join(root, 'snapshots');
  const statePath = path.join(root, 'share-server.json');
  const db = openDatabase(path.join(root, 'test.db'));
  const store = new ReviewStore(db);
  const reader = new SharedSessionReader(store, snapshots);
  let server = new SessionShareServer(store, reader, statePath);
  const git = async (...args: string[]) => (await exec('git', args, { cwd: repo })).stdout;
  try {
    await mkdir(repo);
    await git('init', '-q', '-b', 'feature'); await git('config', 'user.name', 'test'); await git('config', 'user.email', 'test@example.com');
    await writeFile(path.join(repo, 'code.ts'), 'const original = 1;\n');
    await writeFile(path.join(repo, 'deleted.ts'), 'deleted\n');
    await git('add', '.'); await git('commit', '-qm', 'base');
    const base = (await git('rev-parse', 'HEAD')).trim();
    await writeFile(path.join(root, 'private.txt'), 'must never be followed');
    await symlink(path.join(root, 'private.txt'), path.join(repo, 'link.ts'));
    await writeFile(path.join(repo, 'code.ts'), 'const reviewed = 2;\n');
    await writeFile(path.join(repo, '带 空格.ts'), 'const unicode = true;\n');
    await rm(path.join(repo, 'deleted.ts'));
    const source = new LocalWorktreeSource({ source: 'local-worktree', ref: '', repoPath: repo, baseRef: base });
    const prepared = await source.prepare(); const rawDiff = await source.getDiff();
    const remote = store.createReview({ source: 'github-pr', sourceRef: 'acme/repo#1', repoPath: repo, status: 'reviewing' });
    store.setDiff(remote.id, '');
    const local = store.createWorkspaceLocal(remote.id, repo, base, rawDiff, prepared.headSha!);
    await source.saveSnapshot(path.join(snapshots, local.id)); await source.dispose();
    store.startRound(local.id, 1, { headSha: prepared.headSha }); store.finishRound(local.id, 1, 'done');
    const finding = store.addFinding(local.id, { file: 'code.ts', line: 1, severity: 'medium', title: 'review issue', body: 'review evidence' });
    store.addMessage(finding.discussionId, 'user', 'Please fix this exact line');
    const other = store.addFinding(remote.id, { file: 'remote.ts', line: 1, severity: 'low', title: 'remote-only', body: 'not in local share' });
    store.addMessage(other.discussionId, 'user', 'remote-only comment');
    const share = await server.share(local.id);
    assert.match(share.url, /^http:\/\/127\.0\.0\.1:\d+\/sessions\/[A-Za-z0-9_-]{43}$/);
    assert.equal((await server.share(local.id)).url, share.url, 'repeat copy reuses link');
    const context = await (await fetch(share.url)).json();
    assert.equal(context.kind, 'duetlens.shared-review'); assert.equal(context.review.mode, 'local');
    assert.equal(context.review.head, prepared.headSha);
    assert.equal(context.repository.path, repo);
    assert.equal(context.discussions.length, 1);
    assert.equal(context.discussions[0].messages[0].text, 'Please fix this exact line');
    assert.ok(!JSON.stringify(context).includes('remote-only comment'));
    assert.equal((await fetch(share.url)).headers.get('cache-control'), 'no-store');
    assert.equal((await fetch(share.url, { headers: { Origin: 'https://example.com' } })).status, 403);
    const wrongHost = await new Promise<number | undefined>((resolve, reject) => { const req = request(share.url, { headers: { Host: 'example.com' } }, (res) => { res.resume(); resolve(res.statusCode); }); req.on('error', reject); req.end(); });
    assert.equal(wrongHost, 403);
    assert.equal((await fetch(share.url, { method: 'POST' })).status, 405);
    assert.equal((await fetch(share.url.replace(/sessions\/.+/, 'sessions/' + 'x'.repeat(43)))).status, 404);
    const fileUrl = (file: string) => context.files.find((entry: { path: string }) => entry.path === file).url;
    assert.equal(await (await fetch(context.diffUrl)).text(), rawDiff);
    const beforeIndex = await readFile(path.join(repo, '.git/index'));
    await writeFile(path.join(repo, 'code.ts'), 'const changedAfterReview = 3;\n');
    const content = await (await fetch(fileUrl('code.ts'))).json();
    assert.equal(content.content, 'const reviewed = 2;\n', 'read archived reviewed tree, never current disk');
    assert.equal(content.editablePath, path.join(repo, 'code.ts'));
    assert.deepEqual(await readFile(path.join(repo, '.git/index')), beforeIndex);
    assert.equal((await (await fetch(fileUrl('带 空格.ts'))).json()).content, 'const unicode = true;\n');
    const link = await (await fetch(fileUrl('link.ts'))).json();
    assert.equal(link.kind, 'symlink'); assert.equal(link.editablePath, null);
    assert.equal(link.content, path.join(root, 'private.txt'));
    assert.ok(!link.content.includes('must never be followed'));
    assert.equal((await fetch(fileUrl('deleted.ts'))).status, 404);
    const malicious = new URL(fileUrl('code.ts')); malicious.searchParams.set('path', '../private.txt');
    assert.equal((await fetch(malicious)).status, 404);
    malicious.searchParams.set('path', '.git/config'); assert.equal((await fetch(malicious)).status, 404);
    malicious.searchParams.set('path', 'unshared.ts'); assert.equal((await fetch(malicious)).status, 404);
    for (const file of ['', '/absolute', '../x', 'a/../x', 'a\\b', 'a//b', '.git/config', 'a/./b', 'x\0y']) assert.equal(isShareFilePath(file), false);
    store.addMessage(finding.discussionId, 'user', 'New live comment');
    assert.equal((await (await fetch(share.url)).json()).discussions[0].messages.length, 2);
    store.setWorkspaceMode(remote.id, 'remote');
    assert.equal((await (await fetch(share.url)).json()).review.id, local.id, 'mode switch must not retarget shared view');
    const remoteShare = await server.share(remote.id); assert.notEqual(remoteShare.url, share.url);
    assert.equal((await (await fetch(remoteShare.url)).json()).discussions[0].messages[0].text, 'remote-only comment');
    store.startRound(local.id, 2, { headSha: base }); store.finishRound(local.id, 2, 'done');
    assert.equal((await fetch(fileUrl('code.ts'))).status, 409, 'stale revision must require reread');
    assert.equal((await fetch(context.diffUrl)).status, 409);
    await server.close();
    server = new SessionShareServer(store, reader, statePath);
    assert.equal((await server.share(local.id)).url, share.url, 'port and token survive restart');
    assert.equal((await fetch(share.url)).status, 200);
    server.revoke(local.id); assert.equal((await fetch(share.url)).status, 404);
    const replacement = await server.share(local.id); assert.notEqual(replacement.url, share.url);
    assert.equal((await fetch(replacement.url)).status, 200);
    store.deleteReview(remote.id);
    assert.equal((await fetch(replacement.url)).status, 404, 'parent delete cascades local share');
    assert.equal((await fetch(remoteShare.url)).status, 404);
    assert.equal(store.hasReviewShares(), false);
    assert.deepEqual(db.pragma('foreign_key_check'), []);
    console.log('session share: HTTP/no-agent/live comments/view isolation/pinned archived code/Unicode/symlink safety/path limits/version guard/restart/revoke/delete passed');
  } finally { await server.close(); db.close(); await rm(root, { recursive: true, force: true }); }
}
void main().catch((error) => { console.error(error); process.exitCode = 1; });
